//! PRD 0028 RF11.1 — the per-adapter label snapshot.
//!
//! Every adapter that exposes a `label_fixtures` function contributes the
//! metrics its fixture produces. This test records, for each one, the
//! identity a stored series is keyed by (`kind`, `window`, `label`, `unit`,
//! plus `billing`) with its `metric_key`. A change fails the test: decide
//! whether history continues (add an alias to `history::aliases`, PRD 0028
//! RF11.2) or breaks on purpose, then regenerate the snapshot with
//! `CUOTAI_REGENERATE_DOCS=1 cargo test -p cuotai-core label_snapshot`.

use crate::history::metric_key;
use crate::Metric;

const SNAPSHOT: &str = include_str!("label_snapshot.txt");

fn render(fixtures: &[(&str, Vec<Metric>)]) -> String {
    let mut out = String::from(
        "# adapter | metric_key | kind | window | unit | billing | label\n\
         # Generated by `label_snapshot` (PRD 0028 RF11); regenerate with CUOTAI_REGENERATE_DOCS=1.\n",
    );
    for (adapter, metrics) in fixtures {
        for metric in metrics {
            out.push_str(&format!(
                "{adapter} | {} | {:?} | {:?} | {} | {:?} | {}\n",
                &metric_key(metric)[..16],
                metric.kind,
                metric.window,
                metric.unit,
                metric.billing,
                metric.label,
            ));
        }
    }
    out
}

fn fixtures() -> Vec<(&'static str, Vec<Metric>)> {
    use super::*;
    let mut all = Vec::new();
    all.extend(eleven_labs::label_fixtures());
    all.extend(kimchi::label_fixtures());
    all.extend(mimo_platform::label_fixtures());
    all.extend(nine_router::label_fixtures());
    all.extend(router_grok::label_fixtures());
    all.extend(router_keys::label_fixtures());
    all.extend(router_sessions::label_fixtures());
    all
}

#[test]
fn every_fixture_emits_metrics() {
    for (adapter, metrics) in fixtures() {
        assert!(!metrics.is_empty(), "{adapter} fixture emitted no metric");
    }
}

#[test]
fn metric_identities_match_the_snapshot() {
    let current = render(&fixtures());
    if std::env::var_os("CUOTAI_REGENERATE_DOCS").is_some() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("src/providers/label_snapshot.txt");
        std::fs::write(path, &current).unwrap();
        return;
    }
    assert_eq!(
        SNAPSHOT.replace("\r\n", "\n"),
        current,
        "A metric label, kind, window, unit or billing changed. Decide whether history \
         continues: if it does, add (old metric_key, new metric_key) to \
         history::aliases::METRIC_ALIASES; then regenerate with \
         `CUOTAI_REGENERATE_DOCS=1 cargo test -p cuotai-core label_snapshot` and commit the result."
    );
}
