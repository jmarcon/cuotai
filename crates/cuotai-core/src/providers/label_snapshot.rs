/// PRD 0034 RF2: every label, unit and period a fixture produces has a
/// display text: a `metric.*` id, or a text on [`VERBATIM_OK`]. No marker
/// heuristic decides (PRD 0037 re-validation R-02: unaccented Portuguese
/// such as "Vozes personalizadas" has no marker), and the English
/// rendering carries no Portuguese marker nor [`UNACCENTED_PORTUGUESE`]
/// word, so a slot value such as the scope "outro" is caught too.
#[test]
fn every_fixture_text_has_an_english_display_text() {
    use crate::metric_text::metric_text;
    let mut problems = Vec::new();
    for (adapter, metrics) in fixtures() {
        for metric in metrics {
            let texts = [
                Some(&metric.label),
                Some(&metric.unit),
                metric.period.as_ref(),
            ];
            for raw in texts.into_iter().flatten() {
                let text = metric_text(raw);
                let english = text.resolve("en");
                if text.id == "metric.verbatim" && !raw.is_empty() && !verbatim_ok(raw) {
                    problems.push(format!("{adapter}: {raw:?} has no metric.* id"));
                } else if !portuguese_in(&english).is_empty() {
                    problems.push(format!("{adapter}: {raw:?} -> {english:?} is Portuguese"));
                }
            }
        }
    }
    assert!(problems.is_empty(), "{problems:#?}");
}

/// PRD 0037 re-validation V-02: every provider is in [`fixture`]; a
/// [`Fixture::Metrics`] adapter emits metrics and the listed reasons are
/// not empty.
#[test]
fn every_provider_has_a_label_fixture_or_a_reason() {
    let (mut with_metrics, mut named, mut scanned) = (0, 0, 0);
    for provider in every_provider() {
        match fixture(provider) {
            Fixture::Metrics(fixtures) => {
                with_metrics += 1;
                assert!(!fixtures.is_empty(), "{provider:?}");
            }
            Fixture::ProviderNamed(reason) => {
                named += 1;
                assert!(!reason.trim().is_empty(), "{provider:?}");
            }
            Fixture::SourceScan(reason) => {
                scanned += 1;
                assert!(!reason.trim().is_empty(), "{provider:?}");
            }
        }
    }
    assert_eq!(with_metrics + named + scanned, every_provider().len());
    for (text, reason) in VERBATIM_OK.iter().chain(NOT_METRIC_TEXT) {
        assert!(!reason.trim().is_empty(), "{text:?}");
    }
}

/// The surfaces' guard (PRD 0034 re-validation, G9): the adapters' raw
/// labels and units are ids, and no surface shows one. The sentinels are
/// the adapters' own Portuguese texts (every fixture's, plus the Claude,
/// Codex and Copilot ones) wherever a language words them differently;
/// they are rendered through the widget file (every field but the `label`
/// and `unit` ids), the export's display texts, and every event summary,
/// in English, German and Russian (whose plural forms differ most), and
/// none may appear in what a person reads.
#[test]
fn raw_metric_texts_never_reach_a_surface() {
    use crate::events::{Event, EventKind, MetricReading, MetricRef, Values};
    use crate::metric_text::metric_text;
    use crate::text::ParamValue;
    use crate::{Account, Config, MetricKind, Provider, Report, Status};
    use chrono::TimeZone;

    let now = chrono::Utc
        .with_ymd_and_hms(2026, 10, 20, 12, 0, 0)
        .unwrap();
    let mut metrics: Vec<Metric> = fixtures()
        .into_iter()
        .flat_map(|(_, metrics)| metrics)
        .collect();
    for (label, unit) in [
        ("Sessão (5 horas) (%)", "%"),
        ("Semana (7 dias) (%)", "%"),
        ("Codex — janela de 5 hora(s) (%)", "%"),
        (
            "Solicitações premium utilizadas (mês corrente)",
            "solicitações",
        ),
        ("Requisições", "requisições"),
    ] {
        metrics.push(Metric::usage(label, 1.0, unit, MetricKind::Quota, None));
    }
    // Every metric gets a fraction, so the widget file publishes it.
    for metric in &mut metrics {
        metric.kind = MetricKind::Quota;
        metric.billing = crate::Billing::Included;
        metric.used = Some(1.0);
        metric.limit = Some(10.0);
        metric.remaining = None;
    }
    let sentinels = |locale: &str| -> Vec<String> {
        let mut raw: Vec<String> = metrics
            .iter()
            .flat_map(|m| [Some(&m.label), Some(&m.unit), m.period.as_ref()])
            .flatten()
            .filter(|raw| !raw.trim().is_empty() && metric_text(raw).resolve(locale) != **raw)
            .cloned()
            .collect();
        raw.sort();
        raw.dedup();
        raw
    };
    let by_locale: std::collections::BTreeMap<&str, Vec<String>> = ["en-US", "de", "ru"]
        .into_iter()
        .map(|locale| (locale, sentinels(locale)))
        .collect();
    let leaks = |surface: &str, locale: &str, texts: &[String]| -> Vec<String> {
        let mut out = Vec::new();
        for raw in &by_locale[locale] {
            for text in texts {
                if text.contains(raw.as_str()) {
                    out.push(format!("{surface} {locale}: {raw:?} in {text:?}"));
                }
            }
        }
        out
    };
    // The string values of a JSON document outside the raw-id members.
    fn shown(value: &serde_json::Value, out: &mut Vec<String>) {
        match value {
            serde_json::Value::String(text) => out.push(text.clone()),
            serde_json::Value::Array(items) => items.iter().for_each(|v| shown(v, out)),
            serde_json::Value::Object(members) => {
                for (key, v) in members {
                    // The ids themselves (a `Localized`'s `id` names a
                    // catalog entry such as `metric.label.input_tokens`),
                    // and its params (its rendered text is the `fallback`
                    // beside them).
                    if !matches!(key.as_str(), "label" | "unit" | "period" | "params" | "id") {
                        shown(v, out);
                    }
                }
            }
            _ => {}
        }
    }

    // One account per metric: the widget file keeps four per account.
    let accounts: Vec<Account> = (0..metrics.len())
        .map(|i| Account {
            id: None,
            name: format!("Probe {i}"),
            provider: Provider::Groq,
            ..Account::default()
        })
        .collect();
    let config = Config {
        accounts: accounts.clone(),
        ..Config::default()
    };
    let mut cycle = crate::refresh::RefreshCycle::new(&config, std::time::Instant::now());
    for (index, metric) in metrics.iter().enumerate() {
        let report = Report {
            account_id: None,
            diagnostic: None,
            account: accounts[index].name.clone(),
            provider: Provider::Groq,
            checked_at: now,
            status: Status::Ready,
            metrics: vec![metric.clone()],
            notes: Vec::new(),
            notes_l10n: Vec::new(),
            source: String::new(),
            session_expires_at: None,
            sub_reports: Vec::new(),
            as_of: None,
            overage_hint: None,
            breakdown: Vec::new(),
        };
        let token = cycle.begin(index).unwrap();
        cycle.finish_account(index, Some(report), token, std::time::Instant::now());
    }
    let export = crate::export::v1::Export::from_cycle(
        &config,
        &crate::config_file::ConfigIdentity::Explicit("guard".into()),
        &cycle,
        &[],
        now,
        crate::export::v1::Options::default(),
    );
    let mut problems = Vec::new();

    // The export (`--json`): every display text (English fallbacks).
    let mut texts = Vec::new();
    shown(&serde_json::to_value(&export).unwrap(), &mut texts);
    problems.extend(leaks("export", "en-US", &texts));

    // The widget file, written without a language and in German.
    let widgets = crate::widget_snapshot::WidgetSnapshot::from_export(&export, metrics.len());
    assert_eq!(
        widgets.accounts.len(),
        metrics.len(),
        "every probe published"
    );
    for (locale, snapshot) in [
        ("en-US", widgets.clone()),
        ("de", widgets.clone().in_language("de")),
        ("ru", widgets.clone().in_language("ru")),
    ] {
        let mut texts = Vec::new();
        shown(&serde_json::to_value(&snapshot).unwrap(), &mut texts);
        problems.extend(leaks("widget", locale, &texts));
    }

    // Every event summary, about each metric, with every reading.
    let readings: Vec<MetricReading> = metrics
        .iter()
        .map(|m| MetricReading {
            label: m.label.clone(),
            label_text: metric_text(&m.label),
            window: m.window,
            used: m.used,
            limit: m.limit,
            remaining: None,
            unit: m.unit.clone(),
            unit_text: metric_text(&m.unit),
            used_ratio: None,
            resets_at: None,
        })
        .collect();
    for metric in &metrics {
        for kind in EventKind::ALL {
            let event = Event {
                schema: crate::events::SCHEMA,
                event: kind,
                occurred_at: now,
                account_key: "groq:Probe".into(),
                account_id: "acc_probe".into(),
                account_name: "Probe".into(),
                provider: Some(Provider::Groq),
                accounts: Vec::new(),
                parent: None,
                metric: Some(MetricRef::new(metric.label.clone(), metric.window)),
                current: Values {
                    used: Some(2.0),
                    limit: Some(10.0),
                    unit: Some(metric.unit.clone()),
                    unit_text: Some(metric_text(&metric.unit)),
                    spent: Some(2.0),
                    metrics: readings.clone(),
                    ..Values::default()
                },
                previous: Some(Values {
                    limit: Some(5.0),
                    ..Values::default()
                }),
                sample: false,
                row: None,
            };
            for locale in ["en-US", "de", "ru"] {
                let line = event.summary().resolve(locale);
                problems.extend(leaks(kind.name(), locale, &[line]));
            }
        }
    }
    // Paid extra usage counted in each adapter unit (PRD 0034 re-validation,
    // G13): the state line, the chip summaries, the cap and the amount the
    // alerts and events print.
    for metric in metrics.iter().filter(|m| !m.unit.trim().is_empty()) {
        let mut extra = metric.clone();
        extra.used = Some(2.0);
        extra.limit = Some(10.0);
        let report = Report {
            account_id: None,
            diagnostic: None,
            account: "Probe".into(),
            provider: Provider::Groq,
            checked_at: now,
            status: Status::Ready,
            metrics: vec![extra.overage()],
            notes: Vec::new(),
            notes_l10n: Vec::new(),
            source: String::new(),
            session_expires_at: None,
            sub_reports: Vec::new(),
            as_of: None,
            overage_hint: None,
            breakdown: Vec::new(),
        };
        let state = crate::overage::assess(&report).expect("an overage reading");
        let export = crate::overage::OverageExport::from(&state);
        let amounts = [state.cap_amount(), state.amount(), export.amount()];
        for locale in ["en-US", "de", "ru"] {
            let mut lines: Vec<String> = [state.text(), state.summary_with_limit_hit()]
                .iter()
                .map(|text| text.resolve(locale))
                .collect();
            lines.extend(amounts.iter().flatten().map(|amount| match amount {
                ParamValue::Text(text) => text.clone(),
                ParamValue::L10n(text) => text.resolve(locale),
            }));
            problems.extend(leaks("overage", locale, &lines));
        }
    }
    assert!(problems.is_empty(), "{}", problems.join("\n"));
}

