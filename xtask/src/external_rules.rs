//! Monthly drift detection for the external rules and GitHub Actions pins that
//! the release pipeline depends on (PRD 0021 RF9.3).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::time::Duration;

use reqwest::blocking::Client;
use reqwest::header::{ACCEPT, AUTHORIZATION, USER_AGENT};
use semver::Version;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::{err, Error, Res};

const GITHUB_ACCEPT: &str = "application/vnd.github+json";
const USER_AGENT_VALUE: &str = "cuotai-external-rules-check";
const MAX_RESPONSE_BYTES: u64 = 4 * 1024 * 1024;
const INTENTIONALLY_UNVERSIONED_ACTIONS: &[&str] = &["dtolnay/rust-toolchain"];

#[derive(Clone, Debug, Deserialize)]
pub struct Baseline {
    pub schema: u32,
    pub policies: Vec<PolicyBaseline>,
}

#[derive(Clone, Debug, Deserialize)]
pub struct PolicyBaseline {
    pub name: String,
    pub url: String,
    pub sha256: String,
    pub fetched_on: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CheckStatus {
    Unchanged,
    Changed,
    Current,
    Stale,
    PinMismatch,
    CouldNotCheck,
    NotVerifiable,
}

impl CheckStatus {
    fn needs_attention(self) -> bool {
        matches!(
            self,
            Self::Changed | Self::Stale | Self::PinMismatch | Self::CouldNotCheck
        )
    }
}

#[derive(Clone, Debug, Serialize)]
pub struct PolicyResult {
    pub name: String,
    pub url: String,
    pub baseline_sha256: String,
    pub observed_sha256: Option<String>,
    pub status: CheckStatus,
    pub detail: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ActionPin {
    pub action: String,
    pub repository: Option<String>,
    pub sha: String,
    pub version: Option<String>,
    pub locations: Vec<String>,
    pub unsupported_registry: Option<String>,
}

#[derive(Clone, Debug, Serialize)]
pub struct ActionResult {
    pub action: String,
    pub repository: Option<String>,
    pub pinned_sha: String,
    pub pinned_version: Option<String>,
    pub latest_release: Option<String>,
    pub locations: Vec<String>,
    pub status: CheckStatus,
    pub detail: String,
}

#[derive(Clone, Debug, Serialize)]
pub struct Report {
    pub schema: u32,
    pub needs_attention: bool,
    pub policies: Vec<PolicyResult>,
    pub actions: Vec<ActionResult>,
    pub limitations: Vec<String>,
}

impl Report {
    pub fn markdown(&self) -> String {
        let mut out = String::from(
            "# External rules and action pins\n\nThis report is generated by `cargo xtask external-rules-check`. The committed policy hashes are changed only by a reviewed pull request.\n\n",
        );
        out.push_str(if self.needs_attention {
            "## Result: review required\n\n"
        } else {
            "## Result: no drift detected\n\n"
        });
        out.push_str("## Policy pages\n\n| Policy | Result | Baseline SHA-256 | Observed SHA-256 |\n|---|---|---|---|\n");
        for policy in &self.policies {
            writeln!(
                out,
                "| [{}]({}) | `{}` — {} | `{}` | `{}` |",
                escape_markdown(&policy.name),
                policy.url,
                status_name(policy.status),
                escape_markdown(&policy.detail),
                policy.baseline_sha256,
                policy.observed_sha256.as_deref().unwrap_or("unavailable")
            )
            .expect("writing to a String cannot fail");
        }
        out.push_str("\n## GitHub Actions pins\n\n| Action | Result | Pinned | Latest release | Locations |\n|---|---|---|---|---|\n");
        for action in &self.actions {
            write!(
                out,
                "| `{}` | `{}` — {} | ",
                action.action,
                status_name(action.status),
                escape_markdown(&action.detail)
            )
            .expect("writing to a String cannot fail");
            match &action.pinned_version {
                Some(version) => write!(out, "`{version}` at `{}`", action.pinned_sha),
                None => write!(out, "`{}` (no `# vX.Y.Z` comment)", action.pinned_sha),
            }
            .expect("writing to a String cannot fail");
            write!(
                out,
                " | `{}` | ",
                action.latest_release.as_deref().unwrap_or("unavailable")
            )
            .expect("writing to a String cannot fail");
            for (index, location) in action.locations.iter().enumerate() {
                if index > 0 {
                    out.push_str("<br>");
                }
                write!(out, "`{}`", escape_markdown(location))
                    .expect("writing to a String cannot fail");
            }
            out.push_str(" |\n");
        }
        out.push_str("\n## Verification limits\n\n");
        for limit in &self.limitations {
            writeln!(out, "- {limit}").expect("writing to a String cannot fail");
        }
        out
    }
}

pub fn run(repo: &Path, baseline_path: &Path, github_token: Option<&str>) -> Res<Report> {
    let baseline_text = std::fs::read_to_string(baseline_path).map_err(|e| {
        Error::Msg(format!(
            "cannot read external-rules baseline {}: {e}",
            baseline_path.display()
        ))
    })?;
    let baseline: Baseline = serde_json::from_str(&baseline_text).map_err(|e| {
        Error::Msg(format!(
            "invalid external-rules baseline {}: {e}",
            baseline_path.display()
        ))
    })?;
    validate_baseline(&baseline)?;

    let client = Client::builder()
        .timeout(Duration::from_secs(30))
        .redirect(reqwest::redirect::Policy::limited(5))
        .build()
        .map_err(|e| Error::Msg(format!("cannot build HTTP client: {e}")))?;

    let policies: Vec<PolicyResult> = baseline
        .policies
        .iter()
        .map(|policy| match fetch_bytes(&client, &policy.url, None) {
            Ok(first) => {
                let second = fetch_bytes(&client, &policy.url, None);
                assess_policy_samples(policy, Ok(first), second)
            }
            Err(error) => assess_policy(policy, Err(error)),
        })
        .collect();

    let pins = scan_action_pins(&repo.join(".github/workflows"))?;
    let mut latest_cache: BTreeMap<String, Result<Vec<u8>, String>> = BTreeMap::new();
    let mut ref_cache: BTreeMap<(String, String), Result<String, String>> = BTreeMap::new();
    let mut actions = Vec::with_capacity(pins.len());
    for pin in pins {
        let Some(repository) = pin.repository.as_deref() else {
            actions.push(ActionResult {
                action: pin.action,
                repository: None,
                pinned_sha: pin.sha,
                pinned_version: pin.version,
                latest_release: None,
                locations: pin.locations,
                status: CheckStatus::NotVerifiable,
                detail: pin.unsupported_registry.unwrap_or_else(|| {
                    "this action source is not hosted in a GitHub repository".into()
                }),
            });
            continue;
        };
        let Some(version) = pin.version.as_deref() else {
            actions.push(assess_unversioned_action(pin));
            continue;
        };

        let latest = latest_cache
            .entry(repository.to_string())
            .or_insert_with(|| fetch_latest_release(&client, repository, github_token))
            .clone();
        let resolved = ref_cache
            .entry((repository.to_string(), version.to_string()))
            .or_insert_with(|| resolve_tag_commit(&client, repository, version, github_token))
            .clone();
        actions.push(assess_action(pin, latest, resolved));
    }

    let needs_attention = policies
        .iter()
        .any(|result| result.status.needs_attention())
        || actions.iter().any(|result| result.status.needs_attention());
    Ok(Report {
        schema: 1,
        needs_attention,
        policies,
        actions,
        limitations: vec![
            "GitHub-hosted actions with a `# vX.Y.Z` comment are checked through GitHub's official Releases and Git Data APIs; a release tag must resolve to the committed SHA.".into(),
            "A missing or malformed semantic release comment is `could_not_check` and requires attention, except for explicitly known actions whose comments are not action releases.".into(),
            "`dtolnay/rust-toolchain` is intentionally `not_verifiable` because its comment is a Rust toolchain version; its full SHA remains enforced by workflow-check.".into(),
            "A GitHub repository with no published Releases is `not_verifiable` only after the commented tag resolves to the pinned SHA.".into(),
            "Actions from another registry cannot be checked with the GitHub Releases API and are listed as `not_verifiable`, never as current.".into(),
            "An HTTP, API, parsing, authentication, or rate-limit failure is `could_not_check` and requires attention; it is never reported as unchanged or current.".into(),
        ],
    })
}

fn assess_unversioned_action(pin: ActionPin) -> ActionResult {
    let intentionally_unversioned =
        INTENTIONALLY_UNVERSIONED_ACTIONS.contains(&pin.action.as_str());
    ActionResult {
        action: pin.action,
        repository: pin.repository,
        pinned_sha: pin.sha,
        pinned_version: None,
        latest_release: None,
        locations: pin.locations,
        status: if intentionally_unversioned {
            CheckStatus::NotVerifiable
        } else {
            CheckStatus::CouldNotCheck
        },
        detail: if intentionally_unversioned {
            "the comment is a toolchain version, not a GitHub Action release; the SHA is still enforced by workflow-check".into()
        } else {
            "could not check: the pin has no valid `# vX.Y.Z` release comment".into()
        },
    }
}

fn validate_baseline(baseline: &Baseline) -> Res<()> {
    if baseline.schema != 1 {
        return err(format!(
            "unsupported external-rules baseline schema {}",
            baseline.schema
        ));
    }
    if baseline.policies.is_empty() {
        return err("external-rules baseline must contain at least one policy");
    }
    let mut names = BTreeMap::new();
    for policy in &baseline.policies {
        if names.insert(&policy.name, ()).is_some() {
            return err(format!("duplicate policy baseline name: {}", policy.name));
        }
        if !policy.url.starts_with("https://") {
            return err(format!("policy URL must use HTTPS: {}", policy.url));
        }
        if policy.sha256.len() != 64
            || !policy
                .sha256
                .bytes()
                .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
        {
            return err(format!("invalid SHA-256 for policy {}", policy.name));
        }
        if policy.fetched_on.len() != 10 {
            return err(format!("invalid fetch date for policy {}", policy.name));
        }
    }
    Ok(())
}

fn assess_policy_samples(
    baseline: &PolicyBaseline,
    first: Result<Vec<u8>, String>,
    second: Result<Vec<u8>, String>,
) -> PolicyResult {
    match (first, second) {
        (Ok(first), Ok(second)) if first == second => assess_policy(baseline, Ok(first)),
        (Ok(_), Ok(_)) => PolicyResult {
            name: baseline.name.clone(),
            url: baseline.url.clone(),
            baseline_sha256: baseline.sha256.clone(),
            observed_sha256: None,
            status: CheckStatus::CouldNotCheck,
            detail:
                "could not check: source returned different bytes across two consecutive fetches"
                    .into(),
        },
        (Err(error), _) | (_, Err(error)) => assess_policy(baseline, Err(error)),
    }
}

fn assess_policy(baseline: &PolicyBaseline, fetched: Result<Vec<u8>, String>) -> PolicyResult {
    match fetched {
        Ok(content) => {
            let observed = sha256(&content);
            let (status, detail) = if observed == baseline.sha256 {
                (
                    CheckStatus::Unchanged,
                    format!(
                        "content matches the baseline fetched on {}",
                        baseline.fetched_on
                    ),
                )
            } else {
                (
                    CheckStatus::Changed,
                    "content hash differs; review the page and update the baseline only through a pull request".into(),
                )
            };
            PolicyResult {
                name: baseline.name.clone(),
                url: baseline.url.clone(),
                baseline_sha256: baseline.sha256.clone(),
                observed_sha256: Some(observed),
                status,
                detail,
            }
        }
        Err(error) => PolicyResult {
            name: baseline.name.clone(),
            url: baseline.url.clone(),
            baseline_sha256: baseline.sha256.clone(),
            observed_sha256: None,
            status: CheckStatus::CouldNotCheck,
            detail: format!("could not check: {error}"),
        },
    }
}

fn assess_action(
    pin: ActionPin,
    latest: Result<Vec<u8>, String>,
    resolved: Result<String, String>,
) -> ActionResult {
    let repository = pin.repository.clone();
    let mut result = ActionResult {
        action: pin.action,
        repository,
        pinned_sha: pin.sha,
        pinned_version: pin.version,
        latest_release: None,
        locations: pin.locations,
        status: CheckStatus::CouldNotCheck,
        detail: String::new(),
    };
    let resolved = match resolved {
        Ok(sha) => sha,
        Err(error) => {
            result.detail = format!("could not check pinned tag: {error}");
            return result;
        }
    };
    if resolved != result.pinned_sha {
        result.status = CheckStatus::PinMismatch;
        result.detail = format!("the commented tag resolves to {resolved}, not the pinned SHA");
        return result;
    }

    let latest = match latest {
        Ok(json) => match serde_json::from_slice::<LatestRelease>(&json) {
            Ok(release) => release,
            Err(error) => {
                result.detail =
                    format!("could not check: invalid GitHub release response: {error}");
                return result;
            }
        },
        Err(error) => {
            if error.starts_with("no published GitHub release") {
                result.status = CheckStatus::NotVerifiable;
                result.detail = error;
            } else {
                result.detail = format!("could not check: {error}");
            }
            return result;
        }
    };
    result.latest_release = Some(latest.tag_name.clone());

    let Some(pinned_text) = result.pinned_version.as_deref() else {
        result.status = CheckStatus::NotVerifiable;
        result.detail = "missing semantic release comment".into();
        return result;
    };
    let pinned_version = match parse_release_version(pinned_text) {
        Ok(version) => version,
        Err(error) => {
            result.status = CheckStatus::NotVerifiable;
            result.detail = error;
            return result;
        }
    };
    let latest_version = match parse_release_version(&latest.tag_name) {
        Ok(version) => version,
        Err(error) => {
            result.detail = format!("could not compare the latest release: {error}");
            return result;
        }
    };
    if latest_version > pinned_version {
        result.status = CheckStatus::Stale;
        result.detail = format!("newer GitHub release {} is available", latest.tag_name);
    } else {
        result.status = CheckStatus::Current;
        result.detail = if latest_version == pinned_version {
            "pin matches the latest published GitHub release".into()
        } else {
            "pin is newer than GitHub's latest published release".into()
        };
    }
    result
}

#[derive(Deserialize)]
struct LatestRelease {
    tag_name: String,
}

#[derive(Deserialize)]
struct GitRef {
    object: GitObject,
}

#[derive(Deserialize)]
struct GitTag {
    object: GitObject,
}

#[derive(Deserialize)]
struct GitObject {
    #[serde(rename = "type")]
    kind: String,
    sha: String,
}

fn fetch_latest_release(
    client: &Client,
    repository: &str,
    token: Option<&str>,
) -> Result<Vec<u8>, String> {
    let url = format!("https://api.github.com/repos/{repository}/releases/latest");
    match fetch_bytes(client, &url, token) {
        Err(error) if error.contains("HTTP 404") => Err(format!(
            "no published GitHub release exists for {repository}"
        )),
        other => other,
    }
}

fn resolve_tag_commit(
    client: &Client,
    repository: &str,
    tag: &str,
    token: Option<&str>,
) -> Result<String, String> {
    let url = format!("https://api.github.com/repos/{repository}/git/ref/tags/{tag}");
    let bytes = fetch_bytes(client, &url, token)?;
    let reference: GitRef = serde_json::from_slice(&bytes)
        .map_err(|e| format!("invalid GitHub tag-ref response: {e}"))?;
    let mut object = reference.object;
    for _ in 0..4 {
        match object.kind.as_str() {
            "commit" => return Ok(object.sha),
            "tag" => {
                let url = format!(
                    "https://api.github.com/repos/{repository}/git/tags/{}",
                    object.sha
                );
                let bytes = fetch_bytes(client, &url, token)?;
                object = serde_json::from_slice::<GitTag>(&bytes)
                    .map_err(|e| format!("invalid GitHub annotated-tag response: {e}"))?
                    .object;
            }
            kind => {
                return Err(format!(
                    "tag resolves to unsupported Git object type {kind}"
                ))
            }
        }
    }
    Err("annotated tag chain is unexpectedly deep".into())
}

fn fetch_bytes(client: &Client, url: &str, token: Option<&str>) -> Result<Vec<u8>, String> {
    let mut request = client.get(url).header(USER_AGENT, USER_AGENT_VALUE);
    if url.starts_with("https://api.github.com/") {
        request = request.header(ACCEPT, GITHUB_ACCEPT);
        if let Some(token) = token.filter(|token| !token.is_empty()) {
            request = request.header(AUTHORIZATION, format!("Bearer {token}"));
        }
    }
    let response = request
        .send()
        .map_err(|e| format!("request failed for {url}: {e}"))?;
    let status = response.status();
    if !status.is_success() {
        return Err(format!("HTTP {} from {url}", status.as_u16()));
    }
    if response
        .content_length()
        .is_some_and(|length| length > MAX_RESPONSE_BYTES)
    {
        return Err(format!("response from {url} exceeds 4 MiB"));
    }
    let mut bytes = Vec::with_capacity(
        response
            .content_length()
            .unwrap_or_default()
            .min(MAX_RESPONSE_BYTES) as usize,
    );
    response
        .take(MAX_RESPONSE_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| format!("could not read response from {url}: {e}"))?;
    if bytes.len() as u64 > MAX_RESPONSE_BYTES {
        return Err(format!("response from {url} exceeds 4 MiB"));
    }
    Ok(bytes)
}

pub fn scan_action_pins(workflows_dir: &Path) -> Res<Vec<ActionPin>> {
    let mut workflow_paths = workflow_files(workflows_dir)?;
    workflow_paths.sort();
    let mut pins: BTreeMap<(String, String, Option<String>), ActionPin> = BTreeMap::new();
    for path in workflow_paths {
        let text = std::fs::read_to_string(&path)
            .map_err(|e| Error::Msg(format!("cannot read {}: {e}", path.display())))?;
        for (index, line) in text.lines().enumerate() {
            let Some((uses, comment)) = action_use(line) else {
                continue;
            };
            if uses.starts_with("./") {
                continue;
            }
            let Some((action, sha)) = uses.rsplit_once('@') else {
                return err(format!(
                    "{}:{}: action {uses} has no revision",
                    path.display(),
                    index + 1
                ));
            };
            if sha.len() != 40
                || !sha
                    .bytes()
                    .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
            {
                return err(format!(
                    "{}:{}: action {uses} is not pinned to a full lowercase commit SHA",
                    path.display(),
                    index + 1
                ));
            }
            let version = comment.and_then(version_comment);
            let (repository, unsupported_registry) = github_repository(action);
            let location = format!("{}:{}", display_path(&path, workflows_dir), index + 1);
            let key = (action.to_string(), sha.to_string(), version.clone());
            let pin = pins.entry(key).or_insert_with(|| ActionPin {
                action: action.to_string(),
                repository,
                sha: sha.to_string(),
                version,
                locations: Vec::new(),
                unsupported_registry,
            });
            pin.locations.push(location);
        }
    }
    Ok(pins.into_values().collect())
}

pub fn workflow_files(dir: &Path) -> Res<Vec<PathBuf>> {
    let entries = std::fs::read_dir(dir).map_err(|e| {
        Error::Msg(format!(
            "cannot read workflow directory {}: {e}",
            dir.display()
        ))
    })?;
    let mut paths = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| Error::Msg(format!("cannot read workflow entry: {e}")))?;
        let path = entry.path();
        if path
            .extension()
            .and_then(|extension| extension.to_str())
            .is_some_and(|extension| extension == "yml" || extension == "yaml")
        {
            paths.push(path);
        }
    }
    Ok(paths)
}

fn action_use(line: &str) -> Option<(&str, Option<&str>)> {
    let trimmed = line.trim_start();
    let trimmed = trimmed.strip_prefix("- ").unwrap_or(trimmed);
    let value = trimmed.strip_prefix("uses:")?.trim();
    let (uses, comment) = match value.split_once('#') {
        Some((uses, comment)) => (uses.trim(), Some(comment.trim())),
        None => (value, None),
    };
    let uses = uses.trim_matches(['\'', '"']);
    (!uses.is_empty()).then_some((uses, comment))
}

fn version_comment(comment: &str) -> Option<String> {
    let candidate = comment.split_whitespace().next()?;
    parse_release_version(candidate)
        .ok()
        .map(|_| candidate.to_string())
}

fn parse_release_version(value: &str) -> Result<Version, String> {
    let Some(version) = value.strip_prefix('v') else {
        return Err(format!("release version {value:?} does not start with v"));
    };
    Version::parse(version).map_err(|e| format!("invalid semantic release version {value:?}: {e}"))
}

fn github_repository(action: &str) -> (Option<String>, Option<String>) {
    if action.starts_with("docker://") {
        return (
            None,
            Some("Docker-registry actions have no GitHub Releases endpoint that can be derived safely".into()),
        );
    }
    let mut parts = action.split('/');
    let (Some(owner), Some(repo)) = (parts.next(), parts.next()) else {
        return (
            None,
            Some("the action source is not an owner/repository GitHub path".into()),
        );
    };
    (Some(format!("{owner}/{repo}")), None)
}

fn display_path(path: &Path, workflows_dir: &Path) -> String {
    let root = workflows_dir.parent().and_then(Path::parent);
    root.and_then(|root| path.strip_prefix(root).ok())
        .unwrap_or(path)
        .display()
        .to_string()
}

fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

fn status_name(status: CheckStatus) -> &'static str {
    match status {
        CheckStatus::Unchanged => "unchanged",
        CheckStatus::Changed => "changed",
        CheckStatus::Current => "current",
        CheckStatus::Stale => "stale",
        CheckStatus::PinMismatch => "pin_mismatch",
        CheckStatus::CouldNotCheck => "could_not_check",
        CheckStatus::NotVerifiable => "not_verifiable",
    }
}

fn escape_markdown(value: &str) -> String {
    value.replace('|', "\\|").replace('\n', " ")
}

